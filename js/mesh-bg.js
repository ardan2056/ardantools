/* ===== Ardan Tools — Interactive 3D Warped Mesh Background with Sparkling Lines (Berkilau-Kilau) ===== */
(function () {
  'use strict';

  var canvas = document.getElementById('interactive-mesh');
  if (!canvas) {
    canvas = document.createElement('canvas');
    canvas.id = 'interactive-mesh';
    canvas.className = 'interactive-mesh';
    canvas.setAttribute('aria-hidden', 'true');
    document.body.insertBefore(canvas, document.body.firstChild);
  }

  var ctx = canvas.getContext('2d', { alpha: true });
  if (!ctx) return;

  var width = 0;
  var height = 0;
  var dpr = Math.min(window.devicePixelRatio || 1, 2);

  // Mesh Configuration
  var COLS = 16;
  var ROWS = 12;
  var points = [];
  var mouse = {
    x: -9999,
    y: -9999,
    targetX: -9999,
    targetY: -9999,
    active: false,
    radius: 280,
    strength: 45
  };

  // Traveling Light Pulses along lines for glistening shimmer
  var linePulses = [];
  function initPulses() {
    linePulses = [];
    // Horizontal row traveling pulses
    for (var r = 1; r < ROWS; r++) {
      linePulses.push({
        isRow: true,
        idx: r,
        progress: (r * 0.17) % 1,
        speed: 0.10 + (r % 4) * 0.04,
        size: 70 + (r % 3) * 30
      });
    }
    // Vertical column traveling pulses
    for (var c = 1; c < COLS; c++) {
      linePulses.push({
        isRow: false,
        idx: c,
        progress: (c * 0.19) % 1,
        speed: 0.09 + (c % 4) * 0.035,
        size: 70 + (c % 3) * 30
      });
    }
  }

  // Glitter dust particles generated by cursor motion
  var glitterDust = [];

  function Point(col, row, x, y) {
    this.col = col;
    this.row = row;
    this.baseX = x;
    this.baseY = y;
    this.x = x;
    this.y = y;
    this.vx = 0;
    this.vy = 0;
    // Highlight certain intersection points like in the reference image
    this.hasDot = (col + row) % 3 === 0 && col > 0 && col < COLS && row > 0 && row < ROWS;

    // Twinkling sparkle properties
    this.sparklePhase = ((col * 17 + row * 29) % 100) / 100 * Math.PI * 2;
    this.sparkleSpeed = 1.8 + ((col * 7 + row * 11) % 7) * 0.4;
    this.isSparkleStar = (col * 5 + row * 7) % 5 === 0 && col > 0 && col < COLS && row > 0 && row < ROWS;
  }

  function initMesh() {
    points = [];
    var cellW = width / COLS;
    var cellH = height / ROWS;

    // Slight perspective curve / sag so it looks like a 3D undulating grid
    for (var r = 0; r <= ROWS; r++) {
      var rowPoints = [];
      var normY = r / ROWS; // 0 to 1
      for (var c = 0; c <= COLS; c++) {
        var normX = c / COLS; // 0 to 1

        var curveOffset = Math.sin(normX * Math.PI) * (normY * 35 - 15);
        var baseX = c * cellW;
        var baseY = r * cellH + curveOffset;

        var p = new Point(c, r, baseX, baseY);
        rowPoints.push(p);
      }
      points.push(rowPoints);
    }
    initPulses();
  }

  function resize() {
    width = document.documentElement.clientWidth || window.innerWidth;
    height = window.innerHeight;
    canvas.width = Math.floor(width * dpr);
    canvas.height = Math.floor(height * dpr);
    canvas.style.width = '100%';
    canvas.style.height = '100%';
    ctx.setTransform(1, 0, 0, 1, 0, 0);
    ctx.scale(dpr, dpr);
    initMesh();
  }

  // Mouse & Touch tracking
  var lastMouseX = -9999, lastMouseY = -9999;
  function onPointerMove(e) {
    var clientX, clientY;
    if (e.touches && e.touches.length > 0) {
      clientX = e.touches[0].clientX;
      clientY = e.touches[0].clientY;
    } else {
      clientX = e.clientX;
      clientY = e.clientY;
    }
    mouse.targetX = clientX;
    mouse.targetY = clientY;
    mouse.active = true;

    // Spawn sparkle glitter dust when cursor moves
    if (Math.hypot(clientX - lastMouseX, clientY - lastMouseY) > 18) {
      lastMouseX = clientX;
      lastMouseY = clientY;
      if (glitterDust.length < 35) {
        glitterDust.push({
          x: clientX + (Math.random() - 0.5) * 30,
          y: clientY + (Math.random() - 0.5) * 30,
          vx: (Math.random() - 0.5) * 1.2,
          vy: (Math.random() - 0.5) * 1.2 - 0.4,
          size: Math.random() * 4 + 3,
          life: 1.0,
          decay: Math.random() * 0.03 + 0.02
        });
      }
    }
  }

  function onPointerLeave() {
    mouse.active = false;
  }

  window.addEventListener('mousemove', onPointerMove, { passive: true });
  window.addEventListener('touchstart', onPointerMove, { passive: true });
  window.addEventListener('touchmove', onPointerMove, { passive: true });
  window.addEventListener('mouseleave', onPointerLeave, { passive: true });
  window.addEventListener('touchend', onPointerLeave, { passive: true });
  window.addEventListener('resize', resize, { passive: true });

  resize();

  var time = 0;
  var isVisible = true;

  document.addEventListener('visibilitychange', function () {
    isVisible = !document.hidden;
  });

  // Draw 4-point Diamond Star Sparkle (✨)
  function drawDiamondSparkle(x, y, size, alpha) {
    if (alpha <= 0.02) return;
    ctx.save();
    ctx.shadowColor = 'rgba(168, 85, 247, ' + (alpha * 0.95) + ')';
    ctx.shadowBlur = 12 * alpha;

    // Outer cross rays
    ctx.strokeStyle = 'rgba(255, 255, 255, ' + alpha + ')';
    ctx.lineWidth = 1.3;
    ctx.beginPath();
    ctx.moveTo(x - size, y);
    ctx.lineTo(x + size, y);
    ctx.moveTo(x, y - size);
    ctx.lineTo(x, y + size);
    ctx.stroke();

    // Diagonal shimmer rays
    var diag = size * 0.42;
    ctx.strokeStyle = 'rgba(216, 180, 254, ' + (alpha * 0.8) + ')';
    ctx.beginPath();
    ctx.moveTo(x - diag, y - diag);
    ctx.lineTo(x + diag, y + diag);
    ctx.moveTo(x - diag, y + diag);
    ctx.lineTo(x + diag, y - diag);
    ctx.stroke();

    // Central diamond flare
    var core = size * 0.26;
    ctx.fillStyle = 'rgba(255, 255, 255, ' + alpha + ')';
    ctx.beginPath();
    ctx.moveTo(x, y - core);
    ctx.lineTo(x + core, y);
    ctx.lineTo(x, y + core);
    ctx.lineTo(x - core, y);
    ctx.closePath();
    ctx.fill();

    ctx.restore();
  }

  // Get smooth coordinate along a row
  function getPointOnRow(r, progress) {
    var row = points[r];
    if (!row) return null;
    var fIdx = progress * COLS;
    var c1 = Math.floor(fIdx);
    var c2 = Math.min(COLS, c1 + 1);
    var fract = fIdx - c1;
    var p1 = row[c1], p2 = row[c2] || p1;
    return {
      x: p1.x + (p2.x - p1.x) * fract,
      y: p1.y + (p2.y - p1.y) * fract
    };
  }

  // Get smooth coordinate along a column
  function getPointOnCol(c, progress) {
    var fIdx = progress * ROWS;
    var r1 = Math.floor(fIdx);
    var r2 = Math.min(ROWS, r1 + 1);
    var fract = fIdx - r1;
    var p1 = points[r1] && points[r1][c];
    var p2 = points[r2] && points[r2][c] || p1;
    if (!p1) return null;
    return {
      x: p1.x + (p2.x - p1.x) * fract,
      y: p1.y + (p2.y - p1.y) * fract
    };
  }

  function render() {
    if (!isVisible) {
      requestAnimationFrame(render);
      return;
    }

    time += 0.016;

    // Smooth lerp mouse coordinates
    if (mouse.active) {
      mouse.x += (mouse.targetX - mouse.x) * 0.15;
      mouse.y += (mouse.targetY - mouse.y) * 0.15;
    } else {
      mouse.x += (-9999 - mouse.x) * 0.05;
      mouse.y += (-9999 - mouse.y) * 0.05;
    }

    ctx.clearRect(0, 0, width, height);

    // 1. Subtle ambient cursor radial spotlight
    if (mouse.active && mouse.x > -500 && mouse.x < width + 500) {
      var glow = ctx.createRadialGradient(mouse.x, mouse.y, 10, mouse.x, mouse.y, mouse.radius * 1.2);
      glow.addColorStop(0, 'rgba(147, 51, 234, 0.12)');
      glow.addColorStop(0.5, 'rgba(99, 140, 255, 0.06)');
      glow.addColorStop(1, 'rgba(235, 240, 247, 0)');
      ctx.fillStyle = glow;
      ctx.fillRect(0, 0, width, height);
    }

    // 2. Physics & wave calculation for mesh points
    var spring = 0.08;
    var friction = 0.82;

    for (var r = 0; r <= ROWS; r++) {
      var row = points[r];
      for (var c = 0; c <= COLS; c++) {
        var p = row[c];

        // Ambient sine wave floating (breathing grid)
        var waveX = Math.sin(time * 0.8 + r * 0.4 + c * 0.3) * 5;
        var waveY = Math.cos(time * 0.7 + r * 0.3 + c * 0.4) * 6;

        var targetX = p.baseX + waveX;
        var targetY = p.baseY + waveY;

        // Interactive mouse distortion
        if (mouse.active) {
          var dx = p.x - mouse.x;
          var dy = p.y - mouse.y;
          var dist = Math.sqrt(dx * dx + dy * dy);

          if (dist < mouse.radius && dist > 0.001) {
            var factor = (1 - dist / mouse.radius);
            factor = factor * factor;
            var push = factor * mouse.strength;
            targetX += (dx / dist) * push;
            targetY += (dy / dist) * push;
          }
        }

        // Spring acceleration
        p.vx += (targetX - p.x) * spring;
        p.vy += (targetY - p.y) * spring;
        p.vx *= friction;
        p.vy *= friction;
        p.x += p.vx;
        p.y += p.vy;
      }
    }

    // 3. Draw base horizontal grid lines (rows)
    ctx.lineWidth = 1;
    for (var r = 0; r <= ROWS; r++) {
      ctx.beginPath();
      var rRow = points[r];
      ctx.moveTo(rRow[0].x, rRow[0].y);

      for (var c = 1; c <= COLS; c++) {
        var prev = rRow[c - 1];
        var curr = rRow[c];
        var midX = (prev.x + curr.x) / 2;
        var midY = (prev.y + curr.y) / 2;
        ctx.quadraticCurveTo(prev.x, prev.y, midX, midY);
      }
      ctx.lineTo(rRow[COLS].x, rRow[COLS].y);

      var alpha = 0.17 + (r / ROWS) * 0.08;
      ctx.strokeStyle = 'rgba(110, 142, 225, ' + alpha + ')';
      ctx.stroke();
    }

    // 4. Draw base vertical grid lines (columns)
    for (var c = 0; c <= COLS; c++) {
      ctx.beginPath();
      ctx.moveTo(points[0][c].x, points[0][c].y);

      for (var r = 1; r <= ROWS; r++) {
        var prev = points[r - 1][c];
        var curr = points[r][c];
        var midX = (prev.x + curr.x) / 2;
        var midY = (prev.y + curr.y) / 2;
        ctx.quadraticCurveTo(prev.x, prev.y, midX, midY);
      }
      ctx.lineTo(points[ROWS][c].x, points[ROWS][c].y);

      var cAlpha = 0.15 + Math.sin((c / COLS) * Math.PI) * 0.08;
      ctx.strokeStyle = 'rgba(110, 142, 225, ' + cAlpha + ')';
      ctx.stroke();
    }

    // 5. Ambient Diagonal Shimmer Wave (Berkilau Bergelombang)
    // A soft luminous light sweep passing across the lines
    ctx.save();
    for (var r = 0; r <= ROWS; r += 2) {
      var rRow = points[r];
      var wavePhase = Math.sin(time * 1.4 - r * 0.35);
      if (wavePhase > 0.4) {
        var waveAlpha = (wavePhase - 0.4) * 0.45;
        ctx.beginPath();
        ctx.moveTo(rRow[0].x, rRow[0].y);
        for (var c = 1; c <= COLS; c++) {
          var prev = rRow[c - 1];
          var curr = rRow[c];
          ctx.quadraticCurveTo(prev.x, prev.y, (prev.x + curr.x) / 2, (prev.y + curr.y) / 2);
        }
        ctx.lineTo(rRow[COLS].x, rRow[COLS].y);
        ctx.strokeStyle = 'rgba(216, 180, 254, ' + waveAlpha + ')';
        ctx.shadowColor = 'rgba(168, 85, 247, 0.6)';
        ctx.shadowBlur = 6;
        ctx.lineWidth = 1.3;
        ctx.stroke();
      }
    }
    ctx.restore();

    // 6. Glistening Light Pulses (Kilauan Cahaya Berjalan di Garis)
    ctx.save();
    for (var k = 0; k < linePulses.length; k++) {
      var lp = linePulses[k];
      lp.progress = (lp.progress + lp.speed * 0.016) % 1;

      var ptCenter = lp.isRow ? getPointOnRow(lp.idx, lp.progress) : getPointOnCol(lp.idx, lp.progress);
      if (!ptCenter) continue;

      var ptAhead = lp.isRow ?
        getPointOnRow(lp.idx, Math.min(0.999, lp.progress + 0.04)) :
        getPointOnCol(lp.idx, Math.min(0.999, lp.progress + 0.04));
      var ptBehind = lp.isRow ?
        getPointOnRow(lp.idx, Math.max(0.001, lp.progress - 0.04)) :
        getPointOnCol(lp.idx, Math.max(0.001, lp.progress - 0.04));

      if (ptAhead && ptBehind) {
        var grad = ctx.createLinearGradient(ptBehind.x, ptBehind.y, ptAhead.x, ptAhead.y);
        grad.addColorStop(0, 'rgba(168, 85, 247, 0)');
        grad.addColorStop(0.5, 'rgba(255, 255, 255, 0.95)');
        grad.addColorStop(1, 'rgba(147, 51, 234, 0)');

        ctx.strokeStyle = grad;
        ctx.lineWidth = 2.2;
        ctx.shadowColor = 'rgba(192, 132, 252, 0.85)';
        ctx.shadowBlur = 10;
        ctx.beginPath();
        ctx.moveTo(ptBehind.x, ptBehind.y);
        ctx.lineTo(ptCenter.x, ptCenter.y);
        ctx.lineTo(ptAhead.x, ptAhead.y);
        ctx.stroke();

        // Small sparkling star at pulse head
        drawDiamondSparkle(ptCenter.x, ptCenter.y, 4.5, 0.85);
      }
    }
    ctx.restore();

    // 7. Twinkling Diamond Star Sparkles (Bintang Berkilau-Kilau di Persimpangan Garis)
    for (var r = 1; r < ROWS; r++) {
      for (var c = 1; c < COLS; c++) {
        var pt = points[r][c];

        // Draw regular node dots
        if (pt.hasDot) {
          var dMouse = Math.hypot(pt.x - mouse.x, pt.y - mouse.y);
          var isNear = mouse.active && dMouse < mouse.radius;
          var dotRadius = isNear ? 3.8 : 2.5;

          ctx.beginPath();
          ctx.arc(pt.x, pt.y, dotRadius, 0, Math.PI * 2);

          if (isNear) {
            ctx.fillStyle = 'rgba(147, 51, 234, 0.85)';
            ctx.shadowColor = 'rgba(168, 85, 247, 0.9)';
            ctx.shadowBlur = 10;
          } else {
            ctx.fillStyle = 'rgba(110, 142, 225, 0.55)';
            ctx.shadowColor = 'rgba(110, 142, 225, 0.4)';
            ctx.shadowBlur = 4;
          }
          ctx.fill();
          ctx.shadowBlur = 0;
        }

        // Sparkling diamond stars (✨)
        if (pt.isSparkleStar) {
          // Sinusoidal twinkling function with high exponent for bright sparkling flashes
          var twinkle = Math.sin(time * pt.sparkleSpeed + pt.sparklePhase);
          if (twinkle > 0.3) {
            var sparkIntensity = Math.pow((twinkle - 0.3) / 0.7, 3);
            var starSize = 5 + sparkIntensity * 7;
            drawDiamondSparkle(pt.x, pt.y, starSize, sparkIntensity * 0.95);
          }
        }

        // Extra bright sparkles near mouse cursor
        if (mouse.active) {
          var dM = Math.hypot(pt.x - mouse.x, pt.y - mouse.y);
          if (dM < 160) {
            var nearFactor = (1 - dM / 160);
            var cursorSpark = Math.sin(time * 5 + pt.sparklePhase);
            if (cursorSpark > 0) {
              drawDiamondSparkle(pt.x, pt.y, 6 + nearFactor * 5, nearFactor * cursorSpark * 0.9);
            }
          }
        }
      }
    }

    // 8. Render Cursor Glitter Dust Particles
    if (glitterDust.length > 0) {
      for (var g = glitterDust.length - 1; g >= 0; g--) {
        var gd = glitterDust[g];
        gd.x += gd.vx;
        gd.y += gd.vy;
        gd.life -= gd.decay;
        if (gd.life <= 0) {
          glitterDust.splice(g, 1);
        } else {
          drawDiamondSparkle(gd.x, gd.y, gd.size * gd.life, gd.life * 0.9);
        }
      }
    }

    requestAnimationFrame(render);
  }

  requestAnimationFrame(render);
})();

